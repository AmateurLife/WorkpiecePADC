namespace WPADC.Models
{
    /// <summary>
    /// 运动参数模型 —— 保存运动控制卡的速度、加速度、回零等配置。
    /// 这些参数在"参数设置"界面里配置，保存到JSON文件，启动时加载回来。
    /// 每个参数都有单位和典型值，调参的时候参考这些典型值来设。
    /// 注意：这些参数最终会传给固高GTS800运动控制卡，单位必须和控制卡一致（mm/s、mm/s²）。
    /// </summary>
    public class MotionParams
    {
        /// <summary>
        /// 运动速度，单位mm/s，默认10.0。
        /// 这是定位运动（Trap模式）的目标速度，不是点动速度。
        /// 典型值：5~50 mm/s，看工件大小和精度要求，精度要求高的就慢点。
        /// 太快容易过冲，太慢效率低，一般10~20比较常用。
        /// </summary>
        public double Velocity { get; set; } = 10.0;

        /// <summary>
        /// 运动加速度，单位mm/s²，默认1.0。
        /// 这是定位运动从静止加速到目标速度的加速度。
        /// 典型值：0.5~5 mm/s²，加速度太大电机会抖，太小响应慢。
        /// 一般1.0~2.0比较稳，实际调的时候听电机声音，不尖叫不抖就行。
        /// </summary>
        public double Acceleration { get; set; } = 1.0;

        /// <summary>
        /// 回零速度，单位mm/s，默认5.0。
        /// 回零分两个阶段：先快速找限位/原点信号（用这个速度），再慢速精确定位。
        /// 一般设成运动速度的一半左右，太快可能冲过信号。
        /// </summary>
        public double HomeVelocity { get; set; } = 5.0;

        /// <summary>
        /// 回零方向，1为正方向，-1为负方向，默认1。
        /// 这个取决于限位开关和原点信号的物理位置。
        /// 如果原点信号在负方向那边，就设成-1；在正方向就设成1。
        /// 装机的时候定好，一般不会改。
        /// </summary>
        public short HomeDirection { get; set; } = 1;

        /// <summary>
        /// 运动超时时间，单位ms，默认30000.0（30秒）。
        /// 发送运动指令后，如果超过这个时间轴还没到位，就认为运动失败。
        /// 30秒一般够用了，除非行程特别长或者速度特别慢。
        /// 设太短容易误报超时，设太长卡住了要等很久。
        /// </summary>
        public double MotionTimeout { get; set; } = 30000.0;

        /// <summary>
        /// 点动速度，单位mm/s，默认5.0。
        /// 点动就是手动按方向键让平台慢慢移动，用来微调位置或者手动对位。
        /// 一般比定位速度慢一些，方便精确控制，5.0比较常用。
        /// </summary>
        public double JogVelocity { get; set; } = 5.0;

        /// <summary>
        /// 点动加速度，单位mm/s²，默认1.0。
        /// 点动时的加减速，不需要太大，1.0就够了。
        /// 点动讲究的是平稳，不是速度，加速度大了反而不好控制。
        /// </summary>
        public double JogAcceleration { get; set; } = 1.0;
    }

    /// <summary>
    /// 轴状态信息模型 —— 记录单个运动轴的实时状态。
    /// 界面上的状态指示灯、位置显示就是读的这个数据。
    /// 每个轴（X、Y、Z）各有一个实例，通过定时器周期性刷新。
    /// </summary>
    public class AxisStatusInfo
    {
        /// <summary>
        /// 轴索引号，对应运动控制卡上的轴编号。
        /// 固高GTS800最多8个轴，一般我们用：
        ///   1 = X轴，2 = Y轴，3 = Z轴
        /// 注意：固高的轴编号从1开始，不是从0开始。
        /// </summary>
        public short AxisIndex { get; set; }

        /// <summary>
        /// 当前轴位置，单位mm。
        /// 这个是从编码器读回来的实际位置（反馈位置），不是规划位置。
        /// 两个位置的区别：规划位置是控制卡想让轴到的位置，反馈位置是轴实际到的位置。
        /// 如果两者差很多，说明电机跟不上了或者有机械卡顿。
        /// </summary>
        public double Position { get; set; }

        /// <summary>
        /// 轴是否正在运动中。
        /// 通过读取控制卡的状态字判断，用于界面上显示"运行中"指示灯。
        /// 运动中时不能发新的运动指令（得等当前运动完成或停止）。
        /// </summary>
        public bool IsMoving { get; set; }

        /// <summary>
        /// 轴是否已完成回零操作。
        /// 回零成功后设为true。上电后必须先回零才能进行定位运动，
        /// 因为没回零之前控制卡不知道当前位置的绝对坐标。
        /// 如果断电重启，这个标志会丢失，需要重新回零。
        /// </summary>
        public bool IsHomed { get; set; }

        /// <summary>
        /// 轴是否存在报警。
        /// 报警原因可能是：伺服驱动器报错、编码器异常、超程等。
        /// 报警后需要排除故障然后清除报警（GT_AlarmOff），轴才能恢复运动。
        /// </summary>
        public bool HasAlarm { get; set; }

        /// <summary>
        /// 轴是否已使能（伺服使能状态）。
        /// 使能就是给伺服驱动器上电，让电机处于工作状态。
        /// 未使能时电机是自由状态，可以手动转动；使能后电机会锁住，可以接受运动指令。
        /// 一般开机后第一步就是使能所有轴。
        /// </summary>
        public bool IsEnabled { get; set; }
    }
}
